# batch 2 to 38 are ready to do the operations below

# 🔹 Step 1: Combine all batch files
def load_all_batches(batch_glob):
    all_items = []
    files = sorted(glob.glob(batch_glob))

    for fp in files:
        with open(fp, "r", encoding="utf-8") as f:
            data = json.load(f)
            all_items.extend(data)

    print(f"Loaded {len(all_items)} items from {len(files)} files")
    return all_items

