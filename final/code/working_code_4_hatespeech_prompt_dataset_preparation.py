# 🔹 Step 3: Select variant with highest harm level

# We define a deterministic harm score mapping (critical for reviewers).
def select_highest_harm_variant(variants):
    if not variants:
        return None

    # 1️⃣ Check if any variant has a valid harm_score
    scored_variants = []
    for v in variants:
        try:
            if "harm_score" in v and v["harm_score"] is not None:
                scored_variants.append((float(v["harm_score"]), v))
        except (TypeError, ValueError):
            pass

    # If harm_score exists → select highest
    if scored_variants:
        scored_variants.sort(key=lambda x: x[0], reverse=True)
        return scored_variants[0][1]

    # 2️⃣ No harm_score anywhere → select H3 if exists
    for v in variants:
        if v.get("Variant_Level") == "H3":
            return v

    # 3️⃣ Fallback (deterministic): return the last variant
    return variants[-1]



# 🔹 Step 4: Normalize to toxic-dataset schema
def convert_item(item):
    variant = select_highest_harm_variant(item.get("variants", []))
    if not variant:
        return None
    
    
    return {
        "text": item.get("text"),
        "label": item.get("label"),
        "explanation": variant.get("Explanation"),
        "prompt": variant.get("Prompt"),
        "harm_score": str(variant.get("harm_score")),
        "prompt_safety": item.get("prompt_safety", "unsafe"),
        "prompt_safety_reason": item.get("prompt_safety_reason"),
        "response": variant.get("Contextual_Refusal_Response"),
        "aegis_category": item.get("aegis_category"),
        "aegis_reason": item.get("aegis_reason"),
        "aegis_category_name": AEGIS_CATEGORY_MAP.get(
            item.get("aegis_category"), "UNKNOWN"
        )
    }


# 🔹 Step 5 (Optional but Recommended): Deduplicate by prompt
def deduplicate_by_prompt(data):
    seen = set()
    unique = []

    for item in data:
        p = item.get("prompt", "").strip()
        if p and p not in seen:
            seen.add(p)
            unique.append(item)

    return unique

# 🔹 Step 6: Distribution sanity check (optional)
def log_basic_stats(data):
    dist = Counter(item["aegis_category_name"] for item in data)
    print("\nAEGIS Category Name Distribution:")
    for k, v in dist.items():
        print(f"  {k}: {v}")


def main(args):
    # the batch files contains dict object created from rows which are generated by ChatGPT using a prompt
    # manually done this conversion, copied from the ChatGPT chatbox 
    # prompt file: /home/malam10/projects/ai-safety-bangla/final/prompts/hatespeech_to_prompt_conversion_prompt.txt
    raw_items = load_all_batches(args.batch_glob)

    converted = []
    for item in raw_items:
        out = convert_item(item)
        if out:
            converted.append(out)

    print(f"Converted items: {len(converted)}")

    if args.dedup:
        converted = deduplicate_by_prompt(converted)
        print(f"After deduplication: {len(converted)}")

    if args.stats:
        log_basic_stats(converted)

    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(converted, f, ensure_ascii=False, indent=2)

    print(f"\n✅ Final dataset saved to {args.output}")


